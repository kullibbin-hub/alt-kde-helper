#!/bin/bash

echo -e "\033[1;36m========================================\033[0m"
echo -e "\033[1;36mОчистка данных удалённых Flatpak-приложений\033[0m"
echo -e "\033[1;36m========================================\033[0m"

FLATPAK_APP_DATA_DIR="$HOME/.var/app"

fmt_size() {
    local b=$1
    if [ "$b" -ge 1073741824 ]; then
        awk -v b="$b" 'BEGIN{printf "%.1f ГБ", b/1073741824}'
    elif [ "$b" -ge 1048576 ]; then
        awk -v b="$b" 'BEGIN{printf "%.1f МБ", b/1048576}'
    elif [ "$b" -ge 1024 ]; then
        awk -v b="$b" 'BEGIN{printf "%.1f КБ", b/1024}'
    else
        echo "${b} Б"
    fi
}

cleanup_and_exit() {
    rm -f "/tmp/alt-kde-helper-actions/$(basename "$0")"
    exit 0
}

# Возвращает 0, если в папке нет данных пользователя (только служебные файлы KDE или пусто)
is_stub() {
    local dir="$1"
    local host_file="$dir/plasma-browser-integration-host"

    if [ -f "$host_file" ]; then
        if ! grep -qF '# Automatically generated by plasma-browser-integration-flatpak-integrator' "$host_file" 2>/dev/null; then
            return 1
        fi
    fi

    while IFS= read -r f; do
        [ -z "$f" ] && continue
        local base
        base=$(basename "$f")
        if [ "$base" != "plasma-browser-integration-host" ] && [ "$base" != "org.kde.plasma.browser_integration.json" ]; then
            return 1
        fi
    done < <(find "$dir" -type f 2>/dev/null)

    return 0
}

if [ ! -d "$FLATPAK_APP_DATA_DIR" ]; then
    echo -e "\033[1;32m✅ Данных от удалённых приложений не найдено.\033[0m"
    cleanup_and_exit
fi

echo -e "\033[1;33m→ Поиск данных от приложений Flatpak, которых нет в системе...\033[0m"

orphan_apps=()
stub_apps=()
for app_dir in "$FLATPAK_APP_DATA_DIR"/*/; do
    [ -d "$app_dir" ] || continue
    app_id="${app_dir%/}"
    app_id="${app_id##*/}"
    if ! flatpak info "$app_id" &>/dev/null; then
        if is_stub "$app_dir"; then
            stub_apps+=("$app_id")
        else
            orphan_apps+=("$app_id")
        fi
    fi
done

if [ ${#orphan_apps[@]} -eq 0 ] && [ ${#stub_apps[@]} -eq 0 ]; then
    echo -e "\033[1;32m✅ Данных от удалённых приложений не найдено.\033[0m"
    cleanup_and_exit
fi

# Локальные имена из AppStream (только для реальных данных)
declare -A app_names=()
if [ ${#orphan_apps[@]} -gt 0 ] && command -v xmlstarlet >/dev/null 2>&1; then
    for xml_file in /var/lib/flatpak/appstream/*/*/active/appstream.xml; do
        [ -f "$xml_file" ] || continue
        while IFS='|' read -r id name; do
            [ -n "$id" ] && [ -n "$name" ] && app_names["$id"]="$name"
        done < <(xmlstarlet sel -t -m "//component" -v "id" -o "|" \
                        -v "name[not(@xml:lang)]" -n "$xml_file" 2>/dev/null)
    done
fi

# Онлайн-фоллбэк (только для реальных данных)
if [ ${#orphan_apps[@]} -gt 0 ] && command -v curl >/dev/null 2>&1 && command -v python3 >/dev/null 2>&1; then
    for app_id in "${orphan_apps[@]}"; do
        [ -n "${app_names[$app_id]}" ] && continue
        name=$(curl -sf --max-time 5 "https://flathub.org/api/v2/appstream/$app_id" \
               | python3 -c "import sys,json; print(json.load(sys.stdin).get('name',''))" 2>/dev/null)
        [ -n "$name" ] && app_names["$app_id"]="$name"
    done
fi

# Размеры только для реальных данных
declare -A app_sizes=()
total_bytes=0
for app_id in "${orphan_apps[@]}"; do
    size=$(du -sb "$FLATPAK_APP_DATA_DIR/$app_id" 2>/dev/null | cut -f1)
    case "$size" in
        ''|*[!0-9]*) size=0 ;;
    esac
    app_sizes["$app_id"]=$size
    total_bytes=$((total_bytes + size))
done

# Список реальных данных
if [ ${#orphan_apps[@]} -gt 0 ]; then
    echo -e "\033[1;33m→ Найдено данных от удалённых приложений: ${#orphan_apps[@]}\033[0m"
    echo ""
    for app_id in "${orphan_apps[@]}"; do
        sz=$(fmt_size "${app_sizes[$app_id]}")
        if [ -n "${app_names[$app_id]}" ]; then
            echo "  • ${app_names[$app_id]} — $app_id   $sz"
        else
            echo "  • $app_id   $sz"
        fi
    done
    echo ""
fi

# Список служебных папок KDE
if [ ${#stub_apps[@]} -gt 0 ]; then
    echo -e "\033[1;33m→ Найдено служебных папок KDE (без данных пользователя): ${#stub_apps[@]}\033[0m"
    echo ""
    for app_id in "${stub_apps[@]}"; do
        echo "  • $app_id"
    done
    echo ""
fi

# Только заглушки — удаляем без подтверждения
if [ ${#orphan_apps[@]} -eq 0 ]; then
    echo -e "\033[1;33m→ Удаление служебных папок KDE...\033[0m"
    for app_id in "${stub_apps[@]}"; do
        if rm -rf "$FLATPAK_APP_DATA_DIR/$app_id" 2>/dev/null; then
            echo -e "  \033[0;32m🗑 Удалена служебная папка KDE без данных пользователя: $app_id\033[0m"
        else
            echo -e "  \033[1;33m⚠ Не удалось удалить: $app_id\033[0m"
        fi
    done
    echo ""
    echo -e "\033[1;32m✅ Готово. Удалено служебных папок: ${#stub_apps[@]}.\033[0m"
    cleanup_and_exit
fi

# Есть реальные данные — показываем kdialog
total_h=$(fmt_size "$total_bytes")
echo -e "\033[1;33m→ Всего будет освобождено: $total_h\033[0m"
echo ""

if kdialog --yesno "Найдены данные для отсутствующих приложений из Flatpak.\n\nЗанято: $total_h\n\nУдалить? Удаленные папки помещаются в корзину, откуда вы\nможете восстановить те, которые нужны."; then
    removed=0
    for app_id in "${orphan_apps[@]}"; do
        if gio trash -- "$FLATPAK_APP_DATA_DIR/$app_id" 2>/dev/null; then
            echo -e "  \033[0;32m✅ Перемещено в корзину: $app_id\033[0m"
            removed=$((removed + 1))
        else
            echo -e "  \033[1;33m⚠ Не удалось переместить в корзину: $app_id\033[0m"
        fi
    done

    stub_removed=0
    for app_id in "${stub_apps[@]}"; do
        if rm -rf "$FLATPAK_APP_DATA_DIR/$app_id" 2>/dev/null; then
            echo -e "  \033[0;32m🗑 Удалена служебная папка KDE без данных пользователя: $app_id\033[0m"
            stub_removed=$((stub_removed + 1))
        fi
    done

    echo ""
    if [ ${#stub_apps[@]} -gt 0 ]; then
        echo -e "\033[1;32m✅ Готово. Перемещено в корзину: $removed из ${#orphan_apps[@]}, удалено служебных папок: $stub_removed.\033[0m"
    else
        echo -e "\033[1;32m✅ Готово. Перемещено в корзину: $removed из ${#orphan_apps[@]}.\033[0m"
    fi
else
    echo -e "\033[1;33m⏭ Отменено пользователем. Ничего не удалено.\033[0m"
fi

cleanup_and_exit
